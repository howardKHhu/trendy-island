// ─── Helpers ─────────────────────────────────────────────────────────────────

function setText(id, text) {
    const el = document.getElementById(id);
    if (el) el.innerText = text;
}

// ─── Content update ───────────────────────────────────────────────────────────

function updateContent(lang) {
    const data = i18n[lang] || i18n['en'];

    // Page title & meta description (page-aware)
    const path = window.location.pathname;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (path.includes('about')) {
        document.title = data.about_page_title;
        if (metaDesc) metaDesc.setAttribute('content', data.about_meta_description);
    } else if (path.includes('episodes')) {
        document.title = data.episodes_page_title;
        if (metaDesc) metaDesc.setAttribute('content', data.episodes_meta_description);
    } else if (!path.includes('privacy')) {
        document.title = data.page_title;
        if (metaDesc) metaDesc.setAttribute('content', data.meta_description);
    }

    // Nav
    setText('nav-about', data.nav_about);
    setText('nav-episodes', data.nav_episodes);

    // Hero
    setText('hero-title', data.hero_title);
    setText('hero-desc', data.hero_desc);
    const heroCta = document.getElementById('hero-cta');
    if (heroCta) heroCta.innerText = data.hero_cta;

    // About — full paragraphs (about.html)
    setText('about-title', data.about_title);
    const aboutEl = document.getElementById('about-content');
    if (aboutEl) {
        aboutEl.innerHTML = '';
        data.about_content.forEach(para => {
            const p = document.createElement('p');
            p.textContent = para;
            aboutEl.appendChild(p);
        });
    }

    // About — teaser first paragraph (index.html)
    const teaserEl = document.getElementById('about-teaser');
    if (teaserEl) teaserEl.innerText = data.about_content[0];
    setText('about-teaser-cta', data.about_cta);

    // Topics
    setText('topics-title', data.topics_title);
    const tagsContainer = document.getElementById('topics-tags');
    if (tagsContainer) {
        tagsContainer.innerHTML = '';
        data.topics.forEach(tag => {
            const span = document.createElement('span');
            span.className = 'tag';
            span.textContent = tag;
            tagsContainer.appendChild(span);
        });
    }

    // Episodes
    setText('episodes-title', data.episodes_title);
    const loadingEl = document.getElementById('episodes-loading');
    if (loadingEl) loadingEl.innerText = data.episodes_loading;

    // Podcast
    setText('podcast-label', data.podcast_label);
    setText('latest-label', data.latest_label);

    // Footer
    setText('footer-follow', data.footer_follow);
    setText('footer-slogan', data.footer_slogan);
    const privacyEl = document.getElementById('footer-privacy');
    if (privacyEl) privacyEl.textContent = data.footer_privacy;

    // Pass to episodes module if loaded
    if (typeof window.updateEpisodeLang === 'function') {
        window.updateEpisodeLang(data, lang);
    }

    document.documentElement.lang = lang;
}

// ─── Language switch ──────────────────────────────────────────────────────────

function changeLang(lang) {
    localStorage.setItem('preferredLang', lang);
    updateContent(lang);
}

// ─── Back-to-top ─────────────────────────────────────────────────────────────

function scrollToTop() {
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

window.onscroll = function () {
    const btn = document.getElementById('back-to-top');
    if (!btn) return;
    btn.classList.toggle('show', document.documentElement.scrollTop > 400);
};

// ─── Init ─────────────────────────────────────────────────────────────────────

document.addEventListener('DOMContentLoaded', () => {
    // Language detection (same priority as before)
    const urlParams = new URLSearchParams(window.location.search);
    const langParam = urlParams.get('lang');
    const savedLang = localStorage.getItem('preferredLang');
    const browserLang = navigator.language.split('-')[0];
    const supportedLangs = ['zh', 'en', 'ja'];

    const finalLang =
        (langParam && supportedLangs.includes(langParam)) ? langParam :
        (savedLang  && supportedLangs.includes(savedLang))  ? savedLang  :
        supportedLangs.includes(browserLang)                ? browserLang : 'en';

    updateContent(finalLang);
    document.documentElement.lang = finalLang;

    // Active nav link highlight
    const path = window.location.pathname;
    document.querySelectorAll('.nav-link').forEach(link => {
        const page = (link.getAttribute('href') || '').split('/').pop();
        if (page && path.endsWith(page)) link.classList.add('active');
    });

    // Hamburger toggle
    const hamburger = document.getElementById('nav-hamburger');
    const navLinks  = document.getElementById('nav-links');
    if (hamburger && navLinks) {
        hamburger.addEventListener('click', () => {
            const isOpen = navLinks.classList.toggle('open');
            hamburger.classList.toggle('open', isOpen);
            hamburger.setAttribute('aria-expanded', String(isOpen));
            document.body.style.overflow = isOpen ? 'hidden' : '';
        });

        // Close when a nav link is tapped
        navLinks.querySelectorAll('.nav-link').forEach(link => {
            link.addEventListener('click', () => {
                navLinks.classList.remove('open');
                hamburger.classList.remove('open');
                hamburger.setAttribute('aria-expanded', 'false');
                document.body.style.overflow = '';
            });
        });
    }
});
